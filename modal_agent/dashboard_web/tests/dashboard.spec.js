  await page.getByRole('button', { name: 'Completed', exact: true }).click();
  await expect(page.locator('.task-list')).toContainText('Try the research note workflow');
  await page.getByRole('button', { name: 'Active', exact: true }).click();
  await page.getByRole('button', { name: 'Snooze', exact: true }).click();
  await page.getByLabel('New time · Europe/Lisbon').fill('tomorrow at 18:00');
  await page.getByRole('button', { name: 'Snooze task', exact: true }).click();
  await expect(page.locator('.notice[role="status"]')).toContainText('18:00');
  await page.getByRole('button', { name: 'Snoozed', exact: true }).click();
  await expect(page.locator('.task-list')).toContainText('Review the desk setup ideas');
  await noOverflow();
  await go('Memory');
  await expect(page.getByRole('heading', { name: 'Topic recall', exact: true })).toBeVisible();
  const memory = page.locator('.memory-row').filter({ hasText: 'I live in Lisbon.' });
  await memory.getByRole('button', { name: 'Correct', exact: true }).click();
